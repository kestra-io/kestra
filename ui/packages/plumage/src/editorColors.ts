import type {CodeTheme} from "./types.ts"

/** VS Code workbench color ids, which Monaco shares, so one table serves Monaco, VS Code and Expressive Code. */
export function editorColors({editor: e, syntax: s, highContrast}: CodeTheme): Record<string, string> {
    return {
        "editor.background": e.background,
        "editor.foreground": s.text,
        "editor.lineHighlightBackground": e.lineHighlight,
        "editor.lineHighlightBorder": highContrast ? e.widgetBorder : e.lineHighlight,
        "editor.selectionBackground": e.selection,
        "editor.inactiveSelectionBackground": e.selectionInactive,
        "editor.selectionHighlightBackground": e.selectionHighlight,
        "editor.wordHighlightBackground": e.selectionHighlight,
        "editor.wordHighlightStrongBackground": e.selectionHighlight,
        "editor.findMatchBackground": e.findMatch,
        "editor.findMatchHighlightBackground": e.findMatchHighlight,
        "editorCursor.foreground": e.cursor,
        "editorLineNumber.foreground": e.lineNumber,
        "editorLineNumber.activeForeground": e.lineNumberActive,
        "editorIndentGuide.background1": e.indentGuide,
        "editorIndentGuide.activeBackground1": e.indentGuideActive,
        "editorWhitespace.foreground": e.whitespace,
        "editorBracketMatch.background": e.bracketMatch,
        "editorBracketMatch.border": e.indentGuideActive,
        "editorBracketHighlight.foreground1": s.key,
        "editorBracketHighlight.foreground2": s.type,
        "editorBracketHighlight.foreground3": s.number,
        "editorGutter.background": e.background,
        "editorStickyScroll.background": e.background,
        "minimap.background": e.background,
        "editorWidget.background": e.widget,
        "editorWidget.border": e.widgetBorder,
        "editorSuggestWidget.background": e.widget,
        "editorSuggestWidget.border": e.widgetBorder,
        "editorSuggestWidget.foreground": s.text,
        "editorSuggestWidget.highlightForeground": s.key,
        "editorSuggestWidget.selectedBackground": e.selection,
        "editorHoverWidget.background": e.widget,
        "editorHoverWidget.border": e.widgetBorder,
        "editorLink.activeForeground": s.link,
        "editorCodeLens.foreground": s.comment,
        "editorError.foreground": e.error,
        "editorWarning.foreground": e.warning,
        "editorInfo.foreground": e.info,
        "scrollbarSlider.background": e.scrollbar,
        "scrollbarSlider.hoverBackground": e.scrollbarHover,
        "scrollbarSlider.activeBackground": e.scrollbarHover,
        "diffEditor.insertedLineBackground": e.inserted,
        "diffEditor.removedLineBackground": e.removed,
        "diffEditor.insertedTextBackground": "#00000000",
        "editorGroupHeader.tabsBackground": e.widget,
        "editorGroupHeader.tabsBorder": e.widgetBorder,
        "tab.activeBackground": e.background,
        "tab.activeForeground": s.text,
        "tab.activeBorderTop": s.key,
        "titleBar.activeBackground": e.widget,
        "titleBar.activeForeground": e.lineNumber,
        "titleBar.border": e.widgetBorder,
        "terminal.background": e.background,
        "focusBorder": e.cursor,
        ...(highContrast ? {"contrastBorder": e.widgetBorder} : {}),
    }
}
